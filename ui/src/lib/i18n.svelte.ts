const dictionaries = { ru, en };
export type Language = keyof typeof dictionaries;

const state = $state({ lang: 'ru' as Language });

export function resolveLanguage(setting: string): Language {
  if (setting === 'ru' || setting === 'en') return setting;
  return navigator.language.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

export function setLanguage(lang: Language) {
  state.lang = lang;
  document.documentElement.lang = lang;
}

export function currentLanguage(): Language {
  return state.lang;
}

export function t(key: Key | (string & {}), params: Record<string, string | number> = {}): string {
  const k = key as Key;
  let text: string = dictionaries[state.lang][k] ?? ru[k] ?? key;
  for (const [name, value] of Object.entries(params)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
