import { invoke } from '@tauri-apps/api/core';
import type {
  AppUpdate,
  Conflict,
  ConnectionInfo,
  CoreVersions,
  ImportSummary,
  LogEntry,
  NodeStats,
  Profile,
  Settings,
  Snapshot,
  StopResult,
  Subscription,
  TestMethod,
  TrafficSample,
} from './types';

export const api = {
  state: () => invoke<Snapshot>('get_state'),
  importText: (text: string) => invoke<ImportSummary>('import_text', { text }),
  importFile: (path: string) => invoke<ImportSummary>('import_file', { path }),
  saveProfile: (profile: Profile) => invoke<void>('save_profile', { profile }),
  deleteProfiles: (ids: string[]) => invoke<number>('delete_profiles', { ids }),
  removeDuplicates: () => invoke<number>('remove_duplicates'),
  removeUnreachable: (group: string | null) => invoke<number>('remove_unreachable', { group }),
  reorder: (ids: string[]) => invoke<void>('reorder_profiles', { ids }),
  shareLinks: (ids: string[]) => invoke<string>('share_links', { ids }),
  exportProfiles: (ids: string[], path: string) => invoke<void>('export_profiles', { ids, path }),
  exportCoreConfig: (id: string, path: string) => invoke<void>('export_core_config', { id, path }),
  exportBackup: (path: string) => invoke<void>('export_backup', { path }),
  saveSubscription: (subscription: Subscription) => invoke<void>('save_subscription', { subscription }),
  deleteSubscription: (id: string, withProfiles: boolean) => invoke<void>('delete_subscription', { id, withProfiles }),
  updateSubscription: (id: string) => invoke<number>('update_subscription', { id }),
  updateAllSubscriptions: () => invoke<[number, number]>('update_all_subscriptions'),
  connect: (id: string) => invoke<ConnectionInfo>('connect', { id }),
  selectProfile: (id: string) => invoke<void>('select_profile', { id }),
  disconnect: () => invoke<void>('disconnect'),
  saveSettings: (settings: Settings) => invoke<Settings>('save_settings', { settings }),
  startTest: (ids: string[] | null, method: TestMethod) => invoke<number>('start_test', { ids, method }),
  cancelTest: () => invoke<void>('cancel_test'),
  nodeStats: () => invoke<NodeStats[]>('node_stats'),
  traffic: () => invoke<TrafficSample>('traffic'),
  logs: (limit?: number) => invoke<LogEntry[]>('get_logs', { limit }),
  clearLogs: () => invoke<void>('clear_logs'),
  exportLogs: (path: string, format: 'csv' | 'json') => invoke<void>('export_logs', { path, format }),
  processes: () => invoke<string[]>('list_processes'),
  restartAsAdmin: () => invoke<void>('restart_as_admin'),
  coreVersions: () => invoke<CoreVersions>('core_versions'),
  checkAppUpdate: () => invoke<AppUpdate | null>('check_app_update'),
  factoryReset: (everything: boolean) => invoke<Settings>('factory_reset', { everything }),
  detectConflicts: () => invoke<Conflict[]>('detect_conflicts'),
  stopConflicts: (ids: string[]) => invoke<StopResult[]>('stop_conflicts', { ids }),
  updateCore: (kind: 'xray' | 'singbox' | 'geo') => invoke<string>('update_core', { kind }),
  setUiLanguage: (language: string) => invoke<void>('set_ui_language', { language }),
  openDataDir: () => invoke<void>('open_data_dir'),
  openLicensesDir: () => invoke<void>('open_licenses_dir'),
  quit: () => invoke<void>('quit_app'),
};
